function detectBrowserLang(): LangCode {
  if (typeof navigator === "undefined") return "fr";
  const candidates = [navigator.language, ...(navigator.languages ?? [])];
  for (const raw of candidates) {
    if (!raw) continue;
    const lower = raw.toLowerCase();
    // Brazilian Portuguese
    if (lower === "pt-br" || lower.startsWith("pt-br")) return "pt-BR";
    if (lower.startsWith("pt")) return "pt-BR";
    const base = lower.split("-")[0];
    const hit = CODES.find((c) => c.toLowerCase() === lower || c.toLowerCase() === base);
    if (hit) return hit;
  }
  return "fr";
}

type Ctx = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: string) => string;
  modeDescription: (label: string) => string;
  modeLabel: (label: string) => string;
  descUi: (key: string) => string;
};

const I18nContext = createContext<Ctx | null>(null);

const STORAGE_KEY = "modes-usages.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("fr");

  useEffect(() => {
    let initial: LangCode | null = null;
    try {
      const stored = localStorage.getItem(STORAGE_KEY) as LangCode | null;
      if (stored && CODES.includes(stored)) initial = stored;
    } catch {}
    if (!initial) initial = detectBrowserLang();
    setLangState(initial);
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang === "pt-BR" ? "pt-BR" : lang;
    }
  }, [lang]);

  const setLang = (l: LangCode) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch {}
  };

  const value = useMemo<Ctx>(() => ({
    lang,
    setLang,
    t: (key: string) => TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.fr[key] ?? key,
    modeDescription: (label: string) =>
      MODE_DESCRIPTIONS_I18N[lang]?.[label] ?? MODE_DESCRIPTIONS_I18N.fr[label] ?? "",
    modeLabel: (label: string) =>
      MODE_LABELS_I18N[lang]?.[label] ?? label,
    descUi: (key: string) => DESC_UI[lang]?.[key] ?? DESC_UI.fr[key] ?? key,
  }), [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    // Fallback (SSR or before mount): French defaults
    return {
      lang: "fr",
      setLang: () => {},
      t: (key: string) => TRANSLATIONS.fr[key] ?? key,
      modeDescription: (label: string) => MODE_DESCRIPTIONS_I18N.fr[label] ?? "",
      modeLabel: (label: string) => label,
      descUi: (key: string) => DESC_UI.fr[key] ?? key,
    };
  }
  return ctx;
}

/** Render a translated string that may contain simple <strong>...</strong> tags. */
export function THtml({ k, as: Tag = "span", className }: { k: string; as?: keyof React.JSX.IntrinsicElements; className?: string }) {
  const { t } = useI18n();
  return <Tag className={className} dangerouslySetInnerHTML={{ __html: t(k) }} />;
}
